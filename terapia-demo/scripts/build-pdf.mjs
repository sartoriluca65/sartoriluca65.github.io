import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
import './restore-font-source.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=await build({entryPoints:[path.join(root,'src/render.ts')],bundle:true,format:'iife',globalName:'DemoReport',platform:'browser',minify:true,write:false});
const code=output.outputFiles[0].contents,packed=gzipSync(code,{level:9}),revision=createHash('sha256').update(code).digest('hex').slice(0,12),names=[];
for(let start=0,index=0;start<packed.length;start+=65536,index++){
 const name=`assets/report-${revision}-${String(index).padStart(2,'0')}.gzpart`;fs.writeFileSync(path.join(root,name),packed.subarray(start,start+65536));names.push(name);
}
fs.writeFileSync(path.join(root,'assets/report-parts.json'),JSON.stringify(names)+'\n');
fs.writeFileSync(path.join(root,'report-pdf.js'),`/* PDF engine ${revision}: immutable local chunks, generated by scripts/build-pdf.mjs. */
(()=>{const base=new URL('.',document.currentScript.src);globalThis.DemoReportReady=(async()=>{
 const names=${JSON.stringify(names)};
 const chunks=await Promise.all(names.map(async name=>{const r=await fetch(new URL(name,base));if(!r.ok)throw Error('Modulo PDF non disponibile: '+r.status);return new Uint8Array(await r.arrayBuffer());}));
 const packed=new Uint8Array(chunks.reduce((n,b)=>n+b.length,0));let offset=0;for(const part of chunks){packed.set(part,offset);offset+=part.length;}
 const bytes=fflate.gunzipSync(packed),url=URL.createObjectURL(new Blob([bytes],{type:'text/javascript'}));
 try{await new Promise((resolve,reject)=>{const script=document.createElement('script');script.src=url;script.onload=resolve;script.onerror=()=>reject(Error('Modulo PDF non avviato'));document.head.append(script);});}finally{URL.revokeObjectURL(url);}
 return globalThis.DemoReport;
})();globalThis.DemoReportReady.catch(()=>{});})();\n`);
console.log(`PDF engine ${revision}: ${code.length} bytes, ${packed.length} compressed bytes in ${names.length} parts.`);
